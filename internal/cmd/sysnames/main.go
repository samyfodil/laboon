// Command sysnames writes internal/sandbox/lx_sysnames.go: the names of the
// Linux asm-generic syscall numbers the supervisor keys its handlers by and of
// the Linux errnos, from golang.org/x/sys/unix's linux/arm64 tables, and the
// kind of each syscall's arguments, from the kernel's include/linux/syscalls.h.
//
//	go run ./internal/cmd/sysnames "$(go list -m -f '{{.Dir}}' golang.org/x/sys)" \
//		/usr/src/linux-headers-$(uname -r)/include/linux/syscalls.h internal/sandbox/lx_sysnames.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// Argument kinds, one byte each (internal/sandbox/lx_trace.go decodes them).
const (
	kHex     = 'x' // an address, flags, a value shown in hex
	kInt     = 'i' // a 32-bit count, fd or id, in decimal
	kLong    = 'l' // a 64-bit size or offset, in decimal
	kMode    = 'o' // a file mode, in octal
	kDirfd   = 'd' // a directory fd, AT_FDCWD by name
	kStr     = 's' // a C string: a path or a name
	kWbuf    = 'w' // data the call reads from the guest; its length follows
	kRbuf    = 'r' // data the call writes to the guest; its length follows
	kSockadr = 'a' // a socket address; its length follows
)

// overrides are kinds syscalls.h's unnamed parameters cannot tell.
var overrides = map[string]map[int]byte{
	"sendto":   {1: kWbuf},
	"recvfrom": {1: kRbuf},
}

func main() {
	if len(os.Args) != 4 {
		log.Fatal("usage: sysnames XSYS-DIR SYSCALLS.H OUT.go")
	}
	unixDir := filepath.Join(os.Args[1], "unix")
	nums := scan(filepath.Join(unixDir, "zsysnum_linux_arm64.go"), `(?m)^\s*SYS_(\w+)\s*=\s*(\d+)$`)
	errs := scan(filepath.Join(unixDir, "zerrors_linux_arm64.go"), `(?m)^\s*\{(\d+), "(E\w+)", "([^"]*)"\},$`)
	decls := scan(os.Args[2], `asmlinkage long sys_(\w+)\(([^)]*)\);`)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/sysnames from golang.org/x/sys/unix and linux/syscalls.h; DO NOT EDIT.\n\npackage sandbox\n\n")
	b.WriteString("// sysName is the name of Linux asm-generic syscall nr, or \"\" if it has none.\nfunc sysName(nr uint64) string {\n\tswitch nr {\n")
	seen := map[string]bool{}
	sort.Slice(nums, func(i, j int) bool { return atoi(nums[i][2]) < atoi(nums[j][2]) })
	for _, m := range nums {
		if seen[m[2]] {
			continue
		}
		seen[m[2]] = true
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %q\n", m[2], strings.ToLower(m[1]))
	}
	b.WriteString("\t}\n\treturn \"\"\n}\n\n")

	b.WriteString("// sysArgs is the kind of each argument of syscall name, a byte each\n// (lx_trace.go), or \"\" if its arguments are not known.\nfunc sysArgs(name string) string {\n\tswitch name {\n")
	kinds := map[string]string{}
	for _, d := range decls {
		if _, ok := kinds[d[1]]; !ok { // the first of an arch's alternatives
			kinds[d[1]] = argKinds(d[1], d[2])
		}
	}
	names := make([]string, 0, len(kinds))
	for n := range kinds {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %q\n", n, kinds[n])
	}
	b.WriteString("\t}\n\treturn \"\"\n}\n\n")

	b.WriteString("// errnoName is the name and description of Linux errno e, or \"\" if it has none.\nfunc errnoName(e int64) (string, string) {\n\tswitch e {\n")
	for _, m := range errs {
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %q, %q\n", m[1], m[2], m[3])
	}
	b.WriteString("\t}\n\treturn \"\", \"\"\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[3], src, 0o644); err != nil {
		log.Fatal(err)
	}
}

type param struct {
	typ, name    string
	ptr, isConst bool
	stars        int
}

func parse(s string) param {
	var p param
	s = strings.ReplaceAll(s, "*", " * ")
	var words []string
	for _, w := range strings.Fields(s) {
		switch w {
		case "*":
			p.ptr = true
			p.stars++
		case "const":
			p.isConst = true
		case "__user", "struct", "union", "signed":
		default:
			words = append(words, w)
		}
	}
	if len(words) > 1 && words[0] == "unsigned" {
		words = append([]string{"unsigned " + words[1]}, words[2:]...)
	}
	if len(words) > 1 {
		p.name = words[len(words)-1]
	}
	if len(words) > 0 {
		p.typ = words[0]
	}
	return p
}

// argKinds is the kind string of syscall name, declared with parameters ps.
func argKinds(name, ps string) string {
	ps = strings.Join(strings.Fields(ps), " ")
	if ps == "void" || ps == "" {
		return ""
	}
	var params []param
	for _, s := range strings.Split(ps, ",") {
		params = append(params, parse(s))
	}
	k := make([]byte, len(params))
	for i, p := range params {
		lenNext := i+1 < len(params) && !params[i+1].ptr
		k[i] = kind(p, lenNext)
	}
	for i, v := range overrides[name] {
		k[i] = v
	}
	return string(k)
}

func kind(p param, lenNext bool) byte {
	if p.stars > 1 {
		return kHex
	}
	if p.ptr {
		switch {
		case (p.typ == "char" || p.typ == "void") && (p.name == "buf" || p.name == "ubuf") && lenNext:
			if p.isConst {
				return kWbuf
			}
			return kRbuf
		case p.typ == "char" && p.isConst:
			return kStr
		case p.typ == "sockaddr" && lenNext:
			return kSockadr
		}
		return kHex
	}
	switch {
	case slices.Contains([]string{"dfd", "olddfd", "newdfd", "fromdfd", "todfd"}, p.name):
		return kDirfd
	case p.typ == "umode_t" || p.typ == "mode_t":
		return kMode
	case strings.Contains(p.name, "flag") || strings.Contains(p.name, "mask") || p.name == "prot" || p.name == "cmd":
		return kHex
	case slices.Contains([]string{"size_t", "loff_t", "off_t", "ssize_t", "u64", "s64"}, p.typ):
		return kLong
	case slices.Contains([]string{"int", "unsigned int", "unsigned", "pid_t", "uid_t", "gid_t", "old_uid_t",
		"old_gid_t", "u32", "s32", "qid_t", "key_serial_t", "clockid_t", "timer_t", "mqd_t"}, p.typ):
		return kInt
	}
	return kHex
}

func scan(path, re string) [][]string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	m := regexp.MustCompile(re).FindAllStringSubmatch(string(src), -1)
	if len(m) == 0 {
		log.Fatalf("%s: nothing matches %s", path, re)
	}
	return m
}

func atoi(s string) int {
	n, err := strconv.Atoi(s)
	if err != nil {
		log.Fatal(err)
	}
	return n
}
